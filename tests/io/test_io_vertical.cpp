std::vector<float> floats(const uint32_t* b, size_t n) {
    std::vector<float> v(n);
    std::memcpy(v.data(), b, n * 4);
    return v;
}

size_t count_differ(const std::vector<float>& a, const uint32_t* ref, size_t n, const char* what) {
    size_t bad = 0;
    for (size_t i = 0; i < n; ++i) {
        uint32_t u;
        std::memcpy(&u, &a[i], 4);
        if (u != ref[i]) {
            if (bad < 5) {
                float r;
                std::memcpy(&r, &ref[i], 4);
                std::printf("  %s[%zu] (level %d, point %zu): %.9g != %.9g\n", what, i, IL[i / N], i % N, a[i], r);
            }
            ++bad;
        }
    }
    return bad;
}

