int main() {
    int fails = 0;
    auto expect = [&](bool ok, const std::string& what) {
        std::printf("%s %s\n", ok ? "ok  " : "FAIL", what.c_str());
        fails += !ok;
    };

    std::vector<float> p = floats(kP, K * N), t = floats(kT, K * N), u = floats(kU, K * N);
    std::vector<float> hhl = floats(kHHL, (K + 1) * N), ps = floats(kPs, N), hs = floats(kHsurf, N),
                       t2m = floats(kT2m, N);

    clamp_top_pressure(p.data(), N);
    expect(p[0] == 5000.0f && p[1] == floats(kP, 2)[1], "top clamp: 5600 -> 5000.0f, others unchanged");
    check_pressure_increasing(p.data(), K, N);

    std::vector<float> fi(K * N);
    geopotential_from_hhl(hhl.data(), K + 1, N, fi.data());
    expect(count_differ(fi, kFI, K * N, "FI(HHL)") == 0, "geopotential from HHL bitwise (" + std::to_string(K * N) + ")");

    const LogPWeights w = log_p_weights(p.data(), K, N, IL);
    const size_t L = IL.size();
    std::vector<float> out(L * N);
    interpolate_extrapolate(t.data(), K, w, t2m.data(), ps.data(), hs.data(), ExtrapKind::Temperature, EL, out.data());
    expect(count_differ(out, kOutT, L * N, "T") == 0, "T interpolate + extrapolate bitwise (" + std::to_string(L * N) + ")");
    interpolate_extrapolate(u.data(), K, w, t2m.data(), ps.data(), hs.data(), ExtrapKind::LowestLevel, EL, out.data());
    expect(count_differ(out, kOutU, L * N, "U") == 0, "U interpolate + lowest level bitwise");
    interpolate_extrapolate(fi.data(), K, w, t2m.data(), ps.data(), hs.data(), ExtrapKind::Geopotential, EL,
                            out.data());
    expect(count_differ(out, kOutFI, L * N, "FI") == 0, "FI interpolate + extrapolate bitwise");

    // Not extrapolated: levels outside EL stay NaN below the lowest model level.
    interpolate_extrapolate(t.data(), K, w, t2m.data(), ps.data(), hs.data(), ExtrapKind::Temperature, {}, out.data());
    size_t nan = 0, expected_nan = 0;
    for (size_t j = 0; j < L; ++j)
        for (size_t n = 0; n < N; ++n) {
            nan += std::isnan(out[j * N + n]);
            expected_nan += w.k[j * N + n] < 0;
        }
    expect(nan == expected_nan && nan > 0, "no extrapolation: " + std::to_string(nan) + " NaN where unbracketed");

    // A non-monotonic column is an error.
    std::vector<float> q = p;
    q[3 * N + 2] = q[4 * N + 2];
    bool threw = false;
    try {
        check_pressure_increasing(q.data(), K, N);
    } catch (const std::runtime_error&) {
        threw = true;
    }
    expect(threw, "non-increasing pressure throws");
    return fails ? 1 : 0;
}
