"""Calibrate the parity tolerances of one model from the reference's own spreads -> tolerances/<model>.json.

    python -I python/reference/calibrate_tolerances.py --golden-root ROOT --model NAME [--out FILE] [--check OLD.json]

    # reproduce the forecaster's file (reads the read-only reference golden root, writes nothing there):
    .venv/bin/python -I python/reference/calibrate_tolerances.py --golden-root $REF_GOLDEN --model varda \
        --out $VARDA_SCRATCH/jobs/<name>/varda.json --check tolerances/varda.json
    # the temporal downscaler:
    .venv/bin/python -I python/reference/calibrate_tolerances.py --golden-root $VARDA_SCRATCH/golden-ref/varda-td \
        --model varda-td --out tolerances/varda-td.json

A port of the reference repository's calibration script (which generated tolerances/varda.json and dev.json), with the
same rule and constants; only the provenance strings differ (environment variables instead of machine paths).

Inputs: compare_golden.py --json outputs (contract mode) between one model's golden sets, found in ROOT by name (each
may have repeats with a "-rep<N>" suffix; the max over repeats is used):

    compare_cpu-fp32-pyg_vs_cuda-fp32-triton.json        reference GPU fp32 vs CPU ground truth
    compare_cpu-fp32-pyg_vs_cuda-fp16-triton.json        reference GPU fp16 autocast vs CPU ground truth
    compare_cuda-fp32-triton_vs_cuda-fp16-triton.json    reference fp16 vs reference fp32, both GPU

made with `python/reference/compare_golden.py ROOT/cpu-fp32-pyg ROOT/cuda-fp32-triton --json
ROOT/compare_cpu-fp32-pyg_vs_cuda-fp32-triton.json` etc. The checkpoint identity comes from ROOT/cpu-fp32-pyg's
manifest (`checkpoint_identity`, else the uuid/run_id in the anemoi.json of the checkpoint it names); the engine finds
the tolerance file by `checkpoint.uuid`.

Rule (METHOD; per contract key, in rel_absmax):
- exact keys (fp32 input assembly, no GPU arithmetic: in.x, in.x_norm, enc.x_src, enc.x_dst): 1e-6 in every table; the
  reference must show 0 difference on them;
- cuda-fp32 (engine fp32 vs cpu-fp32-pyg): max(1e-5, 3 x reference cuda-fp32 vs cpu);
- cuda-fp16 (engine fp16 vs cpu-fp32-pyg): 1.75 x reference fp16 vs cpu, rounded up to 2 significant digits;
- cuda-fp16-vs-ref-fp16 (engine fp16 vs cuda-fp16-triton): 2 x reference fp16 vs reference fp32, rounded up.

--check OLD regenerates the tables and the reference spreads and exits 1 unless they equal OLD's exactly.
Standard library only.
"""

import argparse
import json
import math
import os
import re
import sys
import zipfile
from pathlib import Path

EXACT = ("in.x", "in.x_norm", "enc.x_src", "enc.x_dst")
TABLES = ("cuda-fp32", "cuda-fp16", "cuda-fp16-vs-ref-fp16")
PAIRS = {  # role -> (ref tag, other tag)
    "cpu-vs-cuda32": ("cpu-fp32-pyg", "cuda-fp32-triton"),
    "cpu-vs-cuda16": ("cpu-fp32-pyg", "cuda-fp16-triton"),
    "cuda32-vs-cuda16": ("cuda-fp32-triton", "cuda-fp16-triton"),
}
FP32_FLOOR, FP32_FACTOR, FP16_FACTOR, VS_REF_FACTOR, EXACT_TOL = 1e-5, 3.0, 1.75, 2.0, 1e-6
METHOD = (
    "All values are rel_absmax (max|a-r|/max|r|, float64; docs/format.md section 2 metric). cuda-fp32: engine GPU fp32 "
    "vs cpu-fp32-pyg; reference cuda-fp32-triton is bitwise deterministic (spread 0), so tol = max(1e-5, 3 x the "
    "reference's own cuda-vs-cpu rel_absmax) per key; keys no GPU op touches (in.*, enc.x_*) get 1e-6. cuda-fp16: "
    "engine fp16-autocast vs cpu-fp32-pyg, tol = 1.75 x the reference fp16's own rel_absmax vs CPU (rounded up, 2 sig. "
    "digits): an independent fp16 implementation has the same error mechanism and magnitude but different roundings; "
    "the max over ~1e7 elements is a stable statistic, so roughly +-30% implementation variability is expected, and 2x "
    "would already hide a mis-placed fp16/fp32 cast; 1.75 keeps headroom without that. 'cuda-fp16-vs-ref-fp16': engine "
    "fp16 vs reference cuda-fp16-triton directly, tol = 2 x the reference fp16-vs-fp32-GPU difference (two independent "
    "roundings add, worst case 2x). Exact keys (fp32 input assembly) 1e-6. proc.*/latent/dec.* are fp16 tensors in "
    "the reference under autocast (stored upcast to fp32); out.pre_bound/out.norm/out.y are fp32. Generated by "
    "python/reference/calibrate_tolerances.py from the compare files listed under 'sources'."
)
# Environment variables whose values are replaced by their names in the provenance strings (longest value first).
NEUTRAL_VARS = ("VARDA_CKPT", "REF_GOLDEN_DEV", "REF_GOLDEN", "REF_SCRATCH", "REF_ROOT", "VARDA_DEV_CKPT",
                "VARDA_SCRATCH")


def neutral(s: str) -> str:
    """Replace machine paths by the environment variables that hold them (tracked files stay environment-neutral)."""
    vals = sorted(((os.environ[v], v) for v in NEUTRAL_VARS if os.environ.get(v)), key=lambda kv: -len(kv[0]))
    for val, name in vals:
        val = val.rstrip("/")
        s = re.sub(re.escape(val) + r"(?=/|\b|$)", f"${name}", s)
    return s


def ceil2(x: float) -> float:
    """Round up to 2 significant digits (0.000903 -> 0.00091)."""
    if x <= 0:
        return x
    e = math.floor(math.log10(x)) - 1
    m = math.ceil(round(x / 10 ** e, 9))
    return float(f"{m}e{e}")


def read_pair(root: Path, ref: str, other: str) -> tuple[dict, list[str]]:
    """{key: max rel_absmax over the repeat files}, [files]."""
    pat = re.compile(rf"^compare_{re.escape(ref)}_vs_{re.escape(other)}(-rep\d+)?\.json$")
    files = sorted(p for p in root.iterdir() if pat.match(p.name))
    if not files:
        raise SystemExit(f"missing {root}/compare_{ref}_vs_{other}.json (python/reference/compare_golden.py --json)")
    out: dict = {}
    for p in files:
        keys = json.loads(p.read_text())["keys"]
        bad = [k for k, e in keys.items() if "error" in e or not math.isfinite(e["rel_absmax"])]
        if bad:
            raise SystemExit(f"{p}: unusable keys {bad}")
        if out and list(keys) != list(out):
            raise SystemExit(f"{p}: keys differ from {files[0]}")
        for k, e in keys.items():
            out[k] = max(out.get(k, 0.0), e["rel_absmax"])
    return out, [p.name for p in files]


def derive(c32: dict, c16: dict, r16: dict) -> dict:
    if not list(c32) == list(c16) == list(r16):
        raise SystemExit("the three comparisons must cover the same keys, in the same order")
    nonzero = {k: (c32[k], c16[k], r16[k]) for k in EXACT if k in c32 and (c32[k] or c16[k] or r16[k])}
    if nonzero:
        raise SystemExit(f"exact keys differ in the reference itself, the 1e-6 rule doesn't apply: {nonzero}")
    out = {t: {} for t in TABLES}
    for k in c32:
        if k in EXACT:
            for t in TABLES:
                out[t][k] = EXACT_TOL
            continue
        out["cuda-fp32"][k] = max(FP32_FLOOR, FP32_FACTOR * c32[k])
        out["cuda-fp16"][k] = ceil2(FP16_FACTOR * c16[k])
        out["cuda-fp16-vs-ref-fp16"][k] = ceil2(VS_REF_FACTOR * r16[k])
    return out


def golden_identity(tag_dir: Path) -> tuple[dict | None, str]:
    """(identity, how) of a golden directory: manifest checkpoint_identity, else uuid/run_id from the checkpoint the
    manifest names (its embedded anemoi-metadata/anemoi.json; plain JSON, no unpickling)."""
    man = json.loads((tag_dir / "manifest.json").read_text())
    ident = man.get("checkpoint_identity")
    if ident and ident.get("uuid"):
        return dict(ident), "manifest checkpoint_identity"
    ck = man.get("checkpoint")
    if not ck or not Path(ck).exists():
        return None, f"no checkpoint_identity and checkpoint {ck!r} not readable"
    with zipfile.ZipFile(ck) as z:
        member = next(n for n in z.namelist() if n.endswith("anemoi-metadata/anemoi.json"))
        meta = json.loads(z.read(member))
    ident = {"uuid": meta.get("uuid"), "run_id": meta.get("run_id"), "size_bytes": Path(ck).stat().st_size,
             "path": ck}
    return ident, f"old manifest without checkpoint_identity: uuid/run_id read from {ck} (path only)"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--golden-root", required=True, help="directory holding the golden tags and compare_*.json")
    ap.add_argument("--model", required=True, help="model name recorded in the file (e.g. varda, varda-td)")
    ap.add_argument("--out", default=None, help="default: tolerances/<model>.json in this repository")
    ap.add_argument("--check", default=None, help="exit 1 unless the tables and spreads equal this file's exactly")
    a = ap.parse_args()
    root = Path(a.golden_root)

    spread, sources = {}, {}
    for role, (ref, other) in PAIRS.items():
        spread[role], sources[role] = read_pair(root, ref, other)
    tol = derive(spread["cpu-vs-cuda32"], spread["cpu-vs-cuda16"], spread["cuda32-vs-cuda16"])

    ident, how = golden_identity(root / "cpu-fp32-pyg")
    if ident is None or not ident.get("uuid"):
        raise SystemExit(f"no checkpoint identity for {root}/cpu-fp32-pyg ({how}): the engine finds tolerances by uuid")
    out = Path(a.out) if a.out else Path(__file__).resolve().parents[2] / "tolerances" / f"{a.model}.json"
    floor_keys = [k for k, v in tol["cuda-fp32"].items() if v == FP32_FLOOR]
    spreads = {f"{o} vs {r}": spread[role] for role, (r, o) in PAIRS.items()}
    doc = {
        "method": METHOD,
        "model": a.model,
        "checkpoint": {k: (neutral(ident[k]) if k == "path" else ident[k])
                       for k in ("uuid", "run_id", "size_bytes", "sha256", "path") if ident.get(k)},
        "checkpoint_identity_source": neutral(how),
        "golden_root": neutral(str(root.resolve())),
        "sources": sources,
        "reference_spread": spreads,
        "notes": {"cuda-fp32 keys at the 1e-5 floor": f"{len(floor_keys)} of {len(tol['cuda-fp32']) - len(EXACT)}"},
        **tol,
    }
    status = 0
    if a.check:
        old = json.loads(Path(a.check).read_text())
        diff = [(t, k, old.get(t, {}).get(k), v) for t in TABLES for k, v in tol[t].items() if old.get(t, {}).get(k) != v]
        diff += [(t, k, v, None) for t in TABLES for k, v in old.get(t, {}).items() if k not in tol[t]]
        diff += [("reference_spread", p) for p in set(spreads) | set(old.get("reference_spread", {}))
                 if spreads.get(p) != old.get("reference_spread", {}).get(p)]
        others = {k: (old.get(k), doc[k]) for k in ("checkpoint", "sources", "notes", "golden_root",
                                                   "checkpoint_identity_source") if old.get(k) != doc[k]}
        print(f"reproduces {a.check} (tables and reference_spread): "
              + ("exactly" if not diff else f"NO, {len(diff)} differences: {diff}"))
        if others:
            print("provenance fields that differ (informational): " + json.dumps(others))
        status = 1 if diff else 0
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = out.with_name(f"{out.name}.tmp.{os.getpid()}")
    tmp.write_text(json.dumps(doc, indent=1) + "\n")
    os.replace(tmp, out)
    print(f"wrote {out} (checkpoint uuid {ident['uuid']}; identity: {neutral(how)})")
    sys.exit(status)


if __name__ == "__main__":
    main()
